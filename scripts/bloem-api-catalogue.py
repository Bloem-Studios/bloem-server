"""Render API documentation coverage from committed contract artifacts."""

import argparse
import json
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = Path("docs/bloem/api-catalogue.md")
NATIVE = "/api/bloem/v1"
METHODS = {"get", "head", "post", "put", "patch", "delete", "options", "trace"}
METHOD_CONSTANTS = {
    "Get": "GET", "Head": "HEAD", "Post": "POST", "Put": "PUT",
    "Patch": "PATCH", "Delete": "DELETE", "Options": "OPTIONS", "Trace": "TRACE",
}


def operations(document):
    return {
        (method.upper(), path): operation
        for path, item in document["paths"].items()
        for method, operation in item.items()
        if method in METHODS
    }


def cell(value):
    return " ".join(str(value).split()).replace("|", "\\|")


def render(v2, native, inventory):
    documented = operations(native)
    v2_operations = operations(v2)
    missing = set()
    dispatchers = set()
    for route in inventory["routes"]:
        path = route["path"]
        if path != NATIVE and not path.startswith(NATIVE + "/"):
            continue
        method = route["method"]
        expression = route.get("handler_expr", "")
        if "*" in path:
            dispatchers.add(path)
            continue
        if route.get("method_origin") == "handle_all":
            match = re.fullmatch(r"methodOnly\(http\.Method(\w+), .+\)", expression)
            if not match or match[1] not in METHOD_CONSTANTS:
                dispatchers.add(path)
                continue
            method = METHOD_CONSTANTS[match[1]]
        if (method, path) not in documented:
            missing.add((method, path, route.get("source_file", "")))

    lines = [
        "# API documentation catalogue", "",
        "Generated by `python3 scripts/bloem-api-catalogue.py`; do not edit the tables by hand.",
        "Regenerate the OpenAPI artifacts and route inventory first. This report reads committed",
        "artifacts; it is not a complete router inventory or evidence of live deployment.", "",
        "## Contract sources", "",
        "| Surface | Typed operations | Contract and usage |",
        "| --- | ---: | --- |",
        f"| Silo native `/api/v2` | {len(v2_operations)} | [OpenAPI](../../contracts/api/v2/openapi.json); [interactive viewer](overlays/api-docs.md) |",
        f"| Bloem extensions `/api/bloem/v1` | {len(documented)} | [OpenAPI](../../contracts/api/bloem/v1/openapi.json); [wire reference](../bloem-api-reference.md) |",
        "| Frozen alpha `/api/v1` | Not generated here | [Contract policy](overlays/architecture/api-contract.md); [route inventory](../../contracts/api/v2/route-inventory.json) |",
        "",
        "OpenAPI documents typed operations, including separately described raw transports.",
        "The inventory also observes mount adapters and all-method chi handlers. A dispatcher",
        "is not a new endpoint for every HTTP verb. This report resolves explicit `methodOnly`",
        "wrappers and keeps other dispatchers separate. Router registration and handler code",
        "remain authoritative; optional routes may depend on configured services.", "",
        "## Typed Bloem operations", "",
        "Use the operation ID to locate request/response schemas in the native OpenAPI file.",
        "Account, profile, organization and platform tokens are distinct; consult each operation's",
        "security declaration and the wire reference before sending credentials or mutations.", "",
        "| Method and path | Operation ID | Description |",
        "| --- | --- | --- |",
    ]
    for (method, path), operation in sorted(documented.items(), key=lambda x: (x[0][1], x[0][0])):
        lines.append(f"| `{method} {path}` | `{cell(operation['operationId'])}` | {cell(operation.get('summary', ''))} |")
    lines += [
        "", "## Inventory entries without typed OpenAPI", "",
        f"The current inventory identifies **{len(missing)}** explicit method/path entries without a",
        "typed native declaration. They require handler-level verification before generating",
        "client calls. A method missing from a documented path still appears here. This is",
        "documentation debt, not an assertion that these routes are unavailable or safe for",
        "unauthenticated callers. Optional groups absent from this inventory can add further gaps.", "",
        "| Observed method and path | Inventory source |", "| --- | --- |",
    ]
    for method, path, source in sorted(missing, key=lambda x: (x[1], x[0], x[2])):
        lines.append(f"| `{method} {path}` | `{cell(source)}` |")
    lines += [
        "", "## Unresolved mount dispatchers", "",
        "Not a callable-operation promise: these entries delegate to another router or handler.",
        "Resolve their registrar and allowed methods before assigning an operation or a schema.", "",
    ]
    lines += [f"- `DISPATCH {path}`" for path in sorted(dispatchers)]
    lines += [
        "", "## Keeping this current", "",
        "```sh", "make apiv2-openapi bloem-openapi route-inventory",
        "python3 scripts/bloem-api-catalogue.py",
        "python3 scripts/bloem-api-catalogue.py --check", "```", "",
        "The [documentation workflow](documentation-workflow.md) covers generation, route-mount",
        "checks, client adoption, documentation ownership and the public-manual structure.", "",
    ]
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail if the catalogue is stale")
    args = parser.parse_args()
    documents = [json.loads((ROOT / name).read_text()) for name in (
        "contracts/api/v2/openapi.json", "contracts/api/bloem/v1/openapi.json",
        "contracts/api/v2/route-inventory.json",
    )]
    report = render(*documents)
    target = ROOT / OUTPUT
    if args.check:
        if not target.exists() or target.read_text() != report:
            parser.exit(1, f"{OUTPUT} is stale; run python3 scripts/bloem-api-catalogue.py\n")
        print(f"{OUTPUT} is current")
    else:
        target.write_text(report)
        print(f"Wrote {OUTPUT}")


if __name__ == "__main__":
    main()
